export interface ParsedAvatarRecipe {
  type: "fan" | "star";
  keys: string[];
  sources: number[];
}

export function buildAvatarRecipe(type: "fan" | "star", keys: string[]): string {
  return `${AVATAR_RECIPE_PREFIX}${type}:${keys.filter((key) => !!AVATAR_ASSETS[key]).join(",")}`;
}

export function parseAvatarRecipe(value: string | null | undefined): ParsedAvatarRecipe | null {
  if (!value?.startsWith(AVATAR_RECIPE_PREFIX)) return null;
  const rest = value.slice(AVATAR_RECIPE_PREFIX.length);
  const separator = rest.indexOf(":");
  if (separator < 0) return null;
  const type = rest.slice(0, separator);
  if (type !== "fan" && type !== "star") return null;
  const keys = rest.slice(separator + 1).split(",").filter((key) => !!AVATAR_ASSETS[key]);
  if (!keys.length) return null;
  return { type, keys, sources: keys.map((key) => AVATAR_ASSETS[key]!) };
}
